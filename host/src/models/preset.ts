import type { Registry, ServerArgs } from "./registry.ts";

/** Seconds the router waits after an unload request before force-killing the model process. */
export const STOP_TIMEOUT_S = 30;

/**
 * Render the registry as a llama.cpp router preset INI (`--models-preset`).
 * Section names are the registry model names, which become the router's model
 * ids. Models whose GGUF is missing are left out so the router never offers
 * them. Registry `defaults` go in `[*]`; per-model `server_args` override them.
 */
export function renderPreset(registry: Registry): string {
	const lines = [
		"; Generated by the Iyye host from config/models.json. Do not edit; it is rewritten on every start.",
		"version = 1",
		"",
		"[*]",
		...argLines(registry.defaults),
		"",
	];
	for (const m of registry.models) {
		if (!m.available) continue;
		lines.push(`[${m.name}]`, `model = ${m.path}`, ...argLines(m.serverArgs), `stop-timeout = ${STOP_TIMEOUT_S}`, "");
	}
	return lines.join("\n");
}

function argLines(args: ServerArgs): string[] {
	return Object.entries(args).map(([k, v]) => `${k} = ${typeof v === "boolean" ? String(v) : v}`);
}
