import type { ModelSpec, Registry, ServerArgs } from "./registry.ts";

/** Seconds the router waits after an unload request before force-killing the model process. */
export const STOP_TIMEOUT_S = 30;

/**
 * Render the registry as a llama.cpp router preset INI (`--models-preset`).
 * Section names are the registry model names, which become the router's model
 * ids. Models whose GGUF is missing are left out so the router never offers
 * them. Registry `defaults` go in `[*]`; per-model `server_args` override them.
 */
export function renderPreset(registry: Registry, opts: { loadMode?: string | null } = {}): string {
	const lines = [
		"; Generated by the Iyye host from config/models.json. Do not edit; it is rewritten on every start.",
		"version = 1",
		"",
		"[*]",
		...argLines(registry.defaults),
		// The host's own setting (IYYE2_LLAMA_LOAD_MODE), not the registry's: it depends on the machine.
		...(opts.loadMode ? [`load-mode = ${opts.loadMode}`] : []),
		"",
	];
	for (const m of registry.models) {
		if (!m.available || m.remote) continue;
		lines.push(
			`[${m.name}]`,
			`model = ${m.path}`,
			...(m.mmproj?.available ? [`mmproj = ${m.mmproj.path}`] : []),
			...argLines(m.serverArgs),
			`stop-timeout = ${STOP_TIMEOUT_S}`,
			"",
		);
	}
	return lines.join("\n");
}

function argLines(args: ServerArgs): string[] {
	return Object.entries(args).map(([k, v]) => `${k} = ${typeof v === "boolean" ? String(v) : v}`);
}

/**
 * The same server arguments as a llama-server command line, for a single model served on its own (plan
 * 0.012: the owner's other machine). Registry `defaults`, then the model's `server_args`, exactly as the
 * preset gives them; a short key (`c`, `np`) is one dash, a long one two; `true` is a bare flag, `false` left out.
 */
export function serverCliArgs(registry: Registry, m: ModelSpec): string[] {
	const out: string[] = [];
	for (const [k, v] of Object.entries({ ...registry.defaults, ...m.serverArgs })) {
		if (v === false) continue;
		out.push(k.length <= 2 ? `-${k}` : `--${k}`);
		if (v !== true) out.push(String(v));
	}
	if (m.mmproj?.available) out.push("--mmproj", m.mmproj.path);
	return out;
}
